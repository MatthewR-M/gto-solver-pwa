import { useMemo, useState } from 'react';
import { className } from '../../engine/cards';
import { RangeGrid } from '../components/RangeGrid';
import { POSITIONS, PREFLOP, weightsFromClassFreq, classWeights } from '../lib/ranges';

type Depth = '50' | '100' | '200';
type Mode = 'rfi' | 'vsOpen' | 'vs3bet';

export function ChartsScreen() {
  const [depth, setDepth] = useState<Depth>('100');
  const [mode, setMode] = useState<Mode>('rfi');
  const [posA, setPosA] = useState('BTN'); // opener / RFI position
  const [posB, setPosB] = useState('BB'); // responder / 3-bettor
  const [action, setAction] = useState<'threeBet' | 'call' | 'fourBet'>('threeBet');
  const [selectedClass, setSelectedClass] = useState<number | null>(null);

  const freqMap = useMemo(() => {
    if (mode === 'rfi') return PREFLOP.rfi[depth]?.[posA] ?? {};
    if (mode === 'vsOpen') {
      const e = PREFLOP.vsOpen[depth]?.[posA]?.[posB];
      return action === 'threeBet' ? (e?.threeBet ?? {}) : (e?.call ?? {});
    }
    const e = PREFLOP.vs3bet[depth]?.[posA]?.[posB];
    return action === 'fourBet' ? (e?.fourBet ?? {}) : (e?.call ?? {});
  }, [depth, mode, posA, posB, action]);

  const values = useMemo(() => classWeights(weightsFromClassFreq(freqMap)), [freqMap]);

  const selectedName = selectedClass !== null ? className(selectedClass) : null;

  return (
    <div className="screen">
      <section className="panel">
        <h2>Preflop charts</h2>
        <p className="muted">
          Generated by this project from Monte Carlo equities plus documented heuristic thresholds
          (see “Method” in the README). These are <strong>not</strong> equilibrium solver output —
          treat them as a reasonable reference baseline.
        </p>
        <div className="row wrap gap">
          <label className="num-field">
            Chart
            <select
              value={mode}
              onChange={(e) => {
                const m = e.target.value as Mode;
                setMode(m);
                if (m === 'vs3bet') setAction('fourBet');
                if (m === 'vsOpen') setAction('threeBet');
              }}
            >
              <option value="rfi">Raise first in</option>
              <option value="vsOpen">Facing an open</option>
              <option value="vs3bet">Facing a 3-bet (as opener)</option>
            </select>
          </label>
          <label className="num-field">
            Depth
            <select value={depth} onChange={(e) => setDepth(e.target.value as Depth)}>
              <option value="50">50bb</option>
              <option value="100">100bb</option>
              <option value="200">200bb</option>
            </select>
          </label>
          <label className="num-field">
            {mode === 'rfi' ? 'Position' : 'Opener'}
            <select value={posA} onChange={(e) => setPosA(e.target.value)}>
              {POSITIONS.map((p) => (
                <option key={p} value={p}>
                  {p}
                </option>
              ))}
            </select>
          </label>
          {mode !== 'rfi' && (
            <label className="num-field">
              {mode === 'vsOpen' ? 'Responder' : '3-bettor'}
              <select value={posB} onChange={(e) => setPosB(e.target.value)}>
                {POSITIONS.map((p) => (
                  <option key={p} value={p}>
                    {p}
                  </option>
                ))}
              </select>
            </label>
          )}
          {mode === 'vsOpen' && (
            <label className="num-field">
              Action
              <select value={action} onChange={(e) => setAction(e.target.value as typeof action)}>
                <option value="threeBet">3-bet</option>
                <option value="call">Call</option>
              </select>
            </label>
          )}
          {mode === 'vs3bet' && (
            <label className="num-field">
              Action
              <select value={action} onChange={(e) => setAction(e.target.value as typeof action)}>
                <option value="fourBet">4-bet</option>
                <option value="call">Call</option>
              </select>
            </label>
          )}
        </div>
        <RangeGrid
          values={values}
          color={action === 'call' ? '100,160,255' : '255,90,90'}
          selectedClass={selectedClass ?? undefined}
          onSelect={setSelectedClass}
        />
        {selectedName && (
          <p>
            <strong>{selectedName}</strong>: frequency {(values[selectedClass!]! * 100).toFixed(0)}%
            {' · '}equity vs a random hand{' '}
            {((PREFLOP.equityVsRandom[selectedName] ?? 0) * 100).toFixed(0)}%
          </p>
        )}
        {Object.keys(freqMap).length === 0 && (
          <p className="muted">No hands in this chart cell (e.g. the position cannot act here).</p>
        )}
      </section>
    </div>
  );
}

